const animeContainer =
    document.getElementById("animeList");

const animeModal =
    document.getElementById("animeModal");

const videoModal =
    document.getElementById("videoModal");

const modalPoster =
    document.getElementById("modalPoster");

const modalTitle =
    document.getElementById("modalTitle");

const modalDescription =
    document.getElementById("modalDescription");

const modalInfo =
    document.getElementById("modalInfo");

const watchButton =
    document.getElementById("watchButton");

const videoPlayer =
    document.getElementById("videoPlayer");

let selectedAnime = null;

function displayAnime(list) {

    animeContainer.innerHTML = "";

    list.forEach(function(anime) {

        const card = document.createElement("div");

        card.className = "anime-card";

        card.dataset.title =
            anime.title.toLowerCase();


        card.innerHTML = `

            <img
                src="${anime.poster}"
                alt="${anime.title}"
                onerror="this.src='https://placehold.co/400x600?text=No+Poster'"
            >

            <div class="anime-info">

                <h3>${anime.title}</h3>

                <p>
                    ${anime.year}
                    •
                    ${anime.episodes} Episodes
                </p>

                <p>
                    ${anime.type}
                </p>

            </div>
        `;


        card.addEventListener(
            "click",
            function() {

                openAnime(anime);

            }
        );


        animeContainer.appendChild(card);

    });

}

function openAnime(anime) {

    selectedAnime = anime;

    modalPoster.src = anime.poster;

    modalPoster.onerror = function() {

        this.src =
            "https://placehold.co/400x600?text=No+Poster";

    };


    modalTitle.innerText =
        anime.title;


    modalDescription.innerText =
        anime.description;


    modalInfo.innerText =
        "⭐ Year: " +
        anime.year +
        "   |   🎬 Episodes: " +
        anime.episodes +
        "   |   📺 Type: " +
        anime.type;


    animeModal.style.display =
        "flex";
}

function closeAnime() {

    animeModal.style.display =
        "none";

}


watchButton.addEventListener(
    "click",
    function() {

        if (!selectedAnime) {
            return;
        }


        if (
            !selectedAnime.videoId ||
            selectedAnime.videoId ===
            "PASTE_VIDEO_ID_HERE"
        ) {

            alert(
                "Please add YouTube Video ID first."
            );

            return;
        }


        videoPlayer.src =
            "https://www.youtube.com/embed/" +
            selectedAnime.videoId +
            "?autoplay=1";


        videoModal.style.display =
            "flex";

    }
);

function closeVideo() {

    videoModal.style.display =
        "none";


    videoPlayer.src = "";

}

function searchAnime() {

    const input =
        document
            .getElementById("searchInput")
            .value
            .toLowerCase()
            .trim();


    const filtered =
        animeList.filter(function(anime) {

            return anime.title
                .toLowerCase()
                .includes(input);

        });


    displayAnime(filtered);

}

document
    .getElementById("searchInput")
    .addEventListener(
        "keydown",
        function(event) {

            if (event.key === "Enter") {

                searchAnime();

            }}
    );
window.addEventListener(
    "click",
    function(event) {

        if (event.target === animeModal) {

            closeAnime();

        }


        if (event.target === videoModal) {

            closeVideo();

        }

    }
);

displayAnime(animeList);